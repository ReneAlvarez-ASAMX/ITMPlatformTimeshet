export type IconName = keyof typeof PATHS;

interface Props {
  name: IconName;
  size?: number;
  /** Relleno sólido (p. ej. estrella marcada como destacada). */
  filled?: boolean;
  className?: string;
}

export function Icon({ name, size = 16, filled = false, className }: Props) {
  return (
    <svg
      className={`icon${className ? ` ${className}` : ""}`}
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill={filled ? "currentColor" : "none"}
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
    >
      {PATHS[name]}
    </svg>
  );
}

